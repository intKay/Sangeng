"""Art-directed surfaces: retain distinct authored materials, separate rug/enamel/bakelite."""
import json
import sys
import subprocess
from pathlib import Path
import numpy as np
from PIL import Image, ImageFilter, ImageDraw

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools/art'))
import artlib as A
TEX=ROOT/'assets/textures';OUT=ROOT/'reports/av-v1.6';OUT.mkdir(parents=True,exist_ok=True)

def periodic_edges(a,width=16):
    a=a.copy()
    for i in range(width):
        w=.5*(1-i/width)**2
        delta=(a[:,i]-a[:,-1-i])*w;a[:,i]-=delta;a[:,-1-i]+=delta
        delta=(a[i]-a[-1-i])*w;a[i]-=delta;a[-1-i]+=delta
    return a

def save(key,a,manifest,base,scale=.006,shine=12,spec='#070706'):
    name='av16_'+key.removeprefix('MAT_')
    if base not in ['enamel','bakelite'] and key!='MAT_rug_faded':a=periodic_edges(a)
    rgb=np.clip(a,0,255).astype('uint8');Image.fromarray(rgb).save(TEX/(name+'.png'),optimize=True)
    previous=TEX/(name+'.jpg')
    if previous.exists():previous.unlink()  # obsolete files generated by this script only
    # Low amplitude, material-specific height. No large colour blobs masquerade as relief.
    gray=Image.fromarray(rgb).convert('L').filter(ImageFilter.GaussianBlur(1.1))
    h=np.asarray(gray,dtype=float);h=(h-np.asarray(gray.filter(ImageFilter.GaussianBlur(5)),dtype=float))*.8+128
    h=periodic_edges(h[:,:,None])[:,:,0]
    Image.fromarray(np.clip(h,0,255).astype('uint8')).save(TEX/(name+'_height.png'))
    d=manifest['materials'][key];d.update(file=name+'.png',tint='#ffffff',bump=name+'_height.png',bumpScale=scale,
      shininess=shine,specular=spec,filter='linear',surfaceClass=base)
    return {'material':key,'class':base,'file':name+'.png','bumpScale':scale,'shininess':shine}

def main():
    manifest=json.loads(subprocess.check_output(['git','show','f669c15:assets/textures/manifest.json'],cwd=ROOT))
    records=[]
    classes={'MAT_wallpaper':'paper','MAT_wallpaper_dark':'paper','MAT_plaster':'plaster','MAT_paint_ceiling':'ceiling',
      'MAT_wood_floor':'floor','MAT_wood_door':'wood','MAT_wood_dark':'wood','MAT_wood_pale':'wood',
      'MAT_curtain':'cloth','MAT_fabric_blue':'cloth','MAT_fabric_white':'cloth',
      'MAT_tile_floor':'tileFloor','MAT_tile_white':'tile','MAT_tile_green':'tile','MAT_metal_locker':'metal'}
    for key,kind in classes.items():
        definition=manifest['materials'][key]
        image=Image.open(TEX/definition['file']).convert('RGB').resize((512,512),Image.Resampling.LANCZOS)
        # Slightly soften old texture grain, keep printed motifs / seams / plank identities.
        a=np.asarray(image.filter(ImageFilter.GaussianBlur(.35)),dtype=float)
        luminance=a@np.array([.299,.587,.114]);a=a*.84+luminance[:,:,None]*.16
        if kind=='floor':
            # Preserve board joints, suppress the old high-contrast chalk speckle.
            soft=np.asarray(image.filter(ImageFilter.GaussianBlur(1.4)),dtype=float)@np.array([.299,.587,.114])
            a=(soft-soft.mean())[:,:,None]*.44+np.array([76,70,59])
        elif kind=='paper':
            src=np.asarray(Image.open(ROOT/'tools/av/sources-v15/wallpaper.png').convert('RGB').resize((512,512)),dtype=float)
            sl=src@np.array([.299,.587,.114]);detail=sl-sl.mean()
            aged=np.asarray(image.filter(ImageFilter.GaussianBlur(12)),dtype=float)
            al=aged@np.array([.299,.587,.114]);al-=al.mean()
            mean=np.array([119,118,97] if key.endswith('dark') else [143,137,113])
            a=mean+detail[:,:,None]*.32+al[:,:,None]*.48
            seams=(np.arange(512)%128<2).astype(float)
            a-=seams[None,:,None]*3
        elif kind=='wood':
            means={'MAT_wood_dark':[79,65,48],'MAT_wood_door':[91,69,48],'MAT_wood_pale':[132,122,104]}
            source='wood_pale' if key=='MAT_wood_pale' else 'wood_door'
            src=np.asarray(Image.open(ROOT/f'tools/av/sources-v15/{source}.png').convert('RGB').resize((512,512)),dtype=float)
            sl=src@np.array([.299,.587,.114])
            # Fine grain under old varnish; broad handling marks, never salt-and-pepper grime.
            r=A.rng('v16-'+key);broad=A.fbm((512,512),3,4,r)
            worn=np.clip((broad-.53)*3,0,.5)
            a=(sl-sl.mean())[:,:,None]*.72+np.array(means[key])
            a+=worn[:,:,None]*np.array([24,23,19])
        elif kind=='ceiling':
            # Preserve age without copying the same dark ring on every ceiling tile.
            src=np.asarray(Image.open(ROOT/'tools/av/sources-v15/plaster.png').convert('RGB').resize((512,512)),dtype=float)
            src=src-src.mean(axis=(0,1))+a.mean(axis=(0,1))
            a=src*.95+a*.05
        elif kind=='plaster':
            src=np.asarray(Image.open(ROOT/'tools/av/sources-v15/plaster.png').convert('RGB').resize((512,512)),dtype=float)
            sl=src@np.array([.299,.587,.114]);fine=luminance-np.asarray(image.filter(ImageFilter.GaussianBlur(4)),dtype=float)@np.array([.299,.587,.114])
            a=(sl-sl.mean())[:,:,None]*1.1+fine[:,:,None]*.12+np.array([162,163,149])
        elif kind=='cloth':
            if key=='MAT_curtain':
                src=np.asarray(Image.open(ROOT/'tools/av/sources-v15/curtain.png').convert('RGB').resize((512,512)),dtype=float)
                sl=src@np.array([.299,.587,.114]);a=(sl-sl.mean())[:,:,None]*.23+np.array([137,128,104])
            else:
                softened=np.asarray(image.filter(ImageFilter.GaussianBlur(2)),dtype=float)
                a=(softened-softened.mean(axis=(0,1)))*.4+np.array([85,101,112] if key.endswith('blue') else [155,147,125])
                yy,xx=np.mgrid[:512,:512];a+=(np.sin(xx*np.pi/2)*np.sin(yy*np.pi/2))[:,:,None]*2
            a+=(A.fbm((512,512),3,4,A.rng('cloth-fade-'+key))[:,:,None]-.5)*16
        scale=.003 if kind in ['paper','cloth'] else .006
        shine=8 if kind in ['paper','plaster','ceiling','cloth'] else 14
        spec='#030302' if kind in ['paper','plaster','ceiling','cloth'] else '#0b0b09'
        if kind in ['tile','metal']:scale=.008;shine=30;spec='#171c18'
        records.append(save(key,a,manifest,kind,scale,shine,spec))
        if key=='MAT_wood_door':manifest['materials'][key]['surfaceClass']='doorWood'
    n=512;yy,xx=np.mgrid[:n,:n];r=A.rng('v16-rug');noise=A.fbm((n,n),4,5,r)
    edge=np.minimum.reduce([xx,yy,n-1-xx,n-1-yy])/n
    weave=(np.sin(xx*np.pi)*np.sin(yy*np.pi))*.8
    rug=np.zeros((n,n,3))+np.array([86,66,49]);rug+=(noise[:,:,None]-.5)*35+weave[:,:,None]
    border=np.exp(-((edge-.055)/.009)**2)+.5*np.exp(-((edge-.08)/.005)**2)
    rug-=border[:,:,None]*np.array([17,10,5])
    center=np.exp(-(((xx-260)/165)**2+((yy-280)/150)**2));rug+=center[:,:,None]*np.array([12,10,8])
    manifest['materials']['MAT_rug_faded']={'colorSpace':'srgb','emissive':None}
    records.append(save('MAT_rug_faded',rug,manifest,'cloth',.002,5,'#020201'))
    # Aged cream enamel: mostly intact paint, localized rim corrosion and small chips.
    r=A.rng('v16-enamel');fine=A.fbm((n,n),9,5,r);broad=A.fbm((n,n),3,4,r)
    enamel=np.zeros((n,n,3))+np.array([181,172,139]);enamel+=(broad[:,:,None]-.5)*14
    rims=np.exp(-yy/28)+np.exp(-(n-1-yy)/20)
    chips=np.clip((fine-.64)/.14,0,1)*np.clip(rims*2.8,0,1)
    enamel=enamel*(1-chips[:,:,None])+np.array([68,53,36])*chips[:,:,None]
    enamel-=rims[:,:,None]*np.array([24,22,18])
    manifest['materials']['MAT_enamel_worn']={'colorSpace':'srgb','emissive':None}
    records.append(save('MAT_enamel_worn',enamel,manifest,'enamel',.002,38,'#28251d'))
    bakelite=np.zeros((n,n,3))+np.array([28,25,21])+(fine[:,:,None]-.5)*10
    manifest['materials']['MAT_bakelite']={'colorSpace':'srgb','emissive':None}
    records.append(save('MAT_bakelite',bakelite,manifest,'bakelite',.001,28,'#1a1711'))
    (TEX/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (OUT/'surfaces.json').write_text(json.dumps(records,indent=2),encoding='utf-8')
    print('Prepared distinct aged surfaces:',len(records),'manifest:',len(manifest['materials']))

if __name__=='__main__':main()
